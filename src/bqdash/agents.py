"""Agent files written into projects: AGENTS.md, CLAUDE.md and skills for Codex and Claude Code.

Every generated file carries a `bqdash:managed` marker. `bqdash agents sync` rewrites marked
files from the installed engine, removes marked skills the engine no longer ships, and never
touches a file without the marker (unless forced). Project knowledge belongs in CONTEXT.md,
which is never managed.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from .config import engine_version

SOURCE = Path(__file__).parent / "template" / "agents"
SKILL_DIRS = (".agents/skills", ".claude/skills")  # Codex, Claude Code
MARKER_RE = re.compile(r"<!-- bqdash:managed version=([^ ]+) [^\n]*-->\n")


def marker(version: str) -> str:
    return (f"<!-- bqdash:managed version={version} - generated by `bqdash agents sync`; "
            "edits are overwritten. Put project notes in CONTEXT.md. -->\n")


def add_marker(text: str, version: str) -> str:
    """Insert the marker; after YAML frontmatter when present (SKILL.md needs it first)."""
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4) + len("\n---\n")
        return text[:end] + marker(version) + text[end:]
    return marker(version) + text


def strip_marker(text: str) -> str:
    return MARKER_RE.sub("", text, count=1)


def is_managed(path: Path) -> bool:
    try:
        return MARKER_RE.search(path.read_text()) is not None
    except (OSError, UnicodeDecodeError):
        return False


def skill_names() -> list[str]:
    return sorted(p.name for p in (SOURCE / "skills").iterdir() if (p / "SKILL.md").exists())


def desired_files() -> dict[str, str]:
    """Relative path -> content without marker."""
    out = {
        "AGENTS.md": (SOURCE / "AGENTS.md").read_text(),
        "CLAUDE.md": (SOURCE / "CLAUDE.md").read_text(),
    }
    for name in skill_names():
        body = (SOURCE / "skills" / name / "SKILL.md").read_text()
        for d in SKILL_DIRS:
            out[f"{d}/{name}/SKILL.md"] = body
    return out


@dataclass
class Action:
    path: str
    status: str  # create | update | unchanged | skip (not managed) | remove


def plan(root: Path, force: bool = False) -> list[Action]:
    actions: list[Action] = []
    for rel, body in desired_files().items():
        p = root / rel
        if not p.exists():
            actions.append(Action(rel, "create"))
        elif not is_managed(p) and not force:
            actions.append(Action(rel, "skip"))
        elif strip_marker(p.read_text()) == body and is_managed(p):
            actions.append(Action(rel, "unchanged"))
        else:
            actions.append(Action(rel, "update"))
    shipped = set(skill_names())
    for d in SKILL_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        for sk in sorted(base.iterdir()):
            f = sk / "SKILL.md"
            if sk.is_dir() and sk.name not in shipped and f.exists() and is_managed(f):
                actions.append(Action(f"{d}/{sk.name}", "remove"))
    return actions


def apply(root: Path, actions: list[Action]) -> None:
    files = desired_files()
    v = engine_version()
    for a in actions:
        p = root / a.path
        if a.status in ("create", "update"):
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(add_marker(files[a.path], v))
        elif a.status == "remove":
            shutil.rmtree(p)


def stale(root: Path) -> list[str]:
    """Managed files that differ from the installed engine's version (for a hint in `up`)."""
    return [a.path for a in plan(root) if a.status in ("update", "remove")]
